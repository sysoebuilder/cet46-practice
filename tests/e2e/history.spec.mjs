import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'
const id = 'CET6-2017-06-2'
const paper = JSON.parse(readFileSync(new URL(`../../src/static/papers/${id}.json`, import.meta.url), 'utf8'))
const previews = 'E:/四六级真题/work/app-previews'
async function openQuestion(page) {
  await page.locator('.floating-answer-button').click()
  await page.locator('.question-summary').first().click()
}
async function choose(page, letter) {
  await openQuestion(page)
  await page.locator('.option').filter({ has: page.locator('.option-label', { hasText: new RegExp(`^${letter}$`) }) }).click()
  await page.locator('.reading-picker .close-button').click()
}

test('history lists attempted papers, resumes responses, and preserves earlier score snapshots', async ({ page }, testInfo) => {
  await page.goto(`/#/pages/practice/index?paper=${id}&section=reading`)
  await choose(page, paper.solutions.items['46'].answer)
  await page.locator('.back-button').click()
  await page.locator('.history-entry').click()
  await expect(page.locator('.history-card')).toHaveCount(1)
  await expect(page.locator('.history-meta')).toContainText('已答 1 / 57')
  await page.locator('.history-continue').click()
  await openQuestion(page)
  await expect(page.locator('.option.chosen .option-label')).toHaveText(paper.solutions.items['46'].answer)
  await page.locator('.reading-picker .close-button').click()
  await page.locator('.practice-score-button').click()
  await expect(page.locator('.estimated-score')).toHaveText('14.2')
  await expect(page.locator('.score-counts')).toContainText('错 54（含空 54）')
  await page.locator('.save-score-button').click()
  await expect(page.locator('.grade-saved')).toHaveText('已保存到历史')
  await page.screenshot({ path: `${previews}/${testInfo.project.name}-score.png`, fullPage: true })
  await page.locator('.back-button').click()
  const other = paper.Reading.passage_comprehension.passages[0].questions[0].options.find(option => option.label !== paper.solutions.items['46'].answer).label
  await choose(page, other)
  await page.locator('.practice-score-button').click()
  await expect(page.locator('.estimated-score')).toHaveText('0.0')
  await expect(page.locator('.score-record-row')).toHaveCount(1)
  await page.locator('.score-record-row').first().click()
  await expect(page.locator('.practice-title')).toHaveText('历史评分')
  await expect(page.locator('.estimated-score')).toHaveText('14.2')
  await expect(page.locator('.save-score-button')).toHaveCount(0)
  await page.locator('.current-score-button').click()
  await expect(page.locator('.estimated-score')).toHaveText('0.0')
  await page.locator('.save-score-button').click()
  await expect(page.locator('.score-record-row')).toHaveCount(2)
  await page.goto('/')
  await page.locator('.history-entry').click()
  await expect(page.locator('.history-card')).toHaveCount(1)
  await expect(page.locator('.history-score')).toContainText('0.0')
  await page.screenshot({ path: `${previews}/${testInfo.project.name}-history.png`, fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
})

test('entirely blank papers can be graded from paper selection and saved into history', async ({ page }) => {
  await page.goto('/')
  await page.locator('.history-entry').click()
  await expect(page.locator('.page-state')).toContainText('还没有做题记录')
  await page.locator('.back-button').click()
  await page.locator('.level-button').filter({ hasText: '六级' }).click()
  await page.locator('.year-chip').filter({ hasText: /^2017$/ }).click()
  await page.locator('.session-card').filter({ has: page.locator('.session-heading', { hasText: /2017\s*\/\s*06/ }) }).locator('.paper-row').filter({ hasText: '第2套' }).click()
  await page.locator('.section-score-button').click()
  await expect(page.locator('.estimated-score')).toHaveText('0.0')
  await expect(page.locator('.score-counts')).toContainText('错 55（含空 55）')
  await expect(page.locator('.score-pending')).toHaveCount(0)
  await page.locator('.save-score-button').click()
  await expect(page.locator('.grade-saved')).toBeVisible()
  await page.goto('/')
  await page.locator('.history-entry').click()
  await expect(page.locator('.history-card')).toHaveCount(1)
  await expect(page.locator('.history-meta')).toContainText('已答 0 / 57')
})

test('written answers wait for valid self scores and edits invalidate earlier self assessments', async ({ page }) => {
  await page.goto(`/#/pages/practice/index?paper=${id}&section=writing`)
  await page.locator('textarea').fill('A first saved writing draft.')
  await page.locator('.practice-score-button').click()
  await expect(page.locator('.score-pending')).toContainText('106.5')
  const field = page.locator('.self-score-input input')
  await field.fill('16')
  await expect(page.locator('.self-score-error')).toHaveText('请输入 0–15')
  await expect(page.locator('.save-score-button')).toHaveAttribute('disabled')
  await field.fill('15')
  await expect(page.locator('.estimated-score')).toHaveText('106.5')
  await expect(page.locator('.score-pending')).toHaveCount(0)
  await page.locator('.save-score-button').click()
  await expect(page.locator('.grade-saved')).toBeVisible()
  await page.locator('.back-button').click()
  await page.locator('textarea').fill('A changed draft must receive a new self assessment.')
  await page.locator('.practice-score-button').click()
  await expect(page.locator('.self-score-input input')).toHaveValue('')
  await expect(page.locator('.score-pending')).toContainText('106.5')
  await expect(page.locator('.estimated-score')).toHaveText('0.0')
  await page.locator('.score-record-row').first().click()
  await expect(page.locator('.estimated-score')).toHaveText('106.5')
})

test('failed score saves remain retryable and never overwrite previous records', async ({ page }) => {
  await page.goto(`/#/pages/score/index?paper=${id}`)
  await page.locator('.save-score-button').click()
  await expect(page.locator('.score-record-row')).toHaveCount(1)
  await page.evaluate(() => {
    const original = Storage.prototype.setItem
    window.restoreScoreStorage = () => { Storage.prototype.setItem = original }
    Storage.prototype.setItem = function(key, value) {
      if (key.startsWith('cet:scores:')) throw new DOMException('Quota exceeded', 'QuotaExceededError')
      return original.call(this, key, value)
    }
  })
  await page.locator('.save-score-button').click()
  await expect(page.locator('.grade-error')).toContainText('评分保存失败')
  await expect(page.locator('.grade-saved')).toHaveCount(0)
  await expect(page.locator('.score-record-row')).toHaveCount(1)
  await page.evaluate(() => window.restoreScoreStorage())
  await page.locator('.save-score-button').click()
  await expect(page.locator('.score-record-row')).toHaveCount(2)
})
